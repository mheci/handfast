//! SFTP serving through a system `sshd`.
//!
//! `kdeconnect.sftp` needs a real SFTP endpoint, and writing an SFTP server is
//! a large amount of code to reimplement. `sshd` is already on every Linux
//! system that could plausibly need this, and its `--` options let a
//! single-use, per-session instance serve exactly one directory.
//!
//! The server is started as:
//!
//! ```text
//! sshd -D -f <generated config> -p <port>
//! ```
//!
//! with a generated config that:
//!
//! - listens on loopback only — the phone reaches it over the KDE Connect
//!   link, and the payload socket is already authenticated. Binding a second
//!   interface would expose the file server to the network;
//! - chroots into the served directory, so the login can read nothing above it;
//! - disables password and keyboard-interactive auth, leaving only the host's
//!   public keys.
//!
//! The port is chosen by binding an ephemeral socket and releasing it. That is
//! a small race, and the alternative — asking `sshd` to bind port 0 — leaves no
//! way to learn which port it chose.

use std::io::Write;
use std::net::TcpListener;
use std::path::PathBuf;
use std::process::{Child, Command, Stdio};
use std::sync::Mutex;

use async_trait::async_trait;

use crate::error::{DesktopError, Result};

/// The program used to serve SFTP.
pub const PROGRAM: &str = "sshd";

/// What the server needs to be told.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ServerRequest {
    /// Directory to serve.
    pub root: String,
    /// Login name reported to the phone.
    pub user: String,
}

impl ServerRequest {
    /// Reject a root that could escape its own chroot.
    ///
    /// The path is embedded in a generated `sshd` config, so it must be
    /// absolute and free of newlines: a newline would let a configured value
    /// inject additional directives.
    ///
    /// # Errors
    ///
    /// Fails for a relative or empty path, or one holding a newline.
    pub fn validate(&self) -> Result<()> {
        if self.root.trim().is_empty() {
            return Err(DesktopError::Backend(
                "no SFTP root is configured".to_string(),
            ));
        }
        if !self.root.starts_with('/') {
            return Err(DesktopError::Backend(
                "the SFTP root must be an absolute path".to_string(),
            ));
        }
        if self.root.contains('\n') || self.root.contains('\r') {
            return Err(DesktopError::Backend(
                "the SFTP root must not contain a newline".to_string(),
            ));
        }
        if self.user.trim().is_empty() || self.user.chars().any(char::is_whitespace) {
            return Err(DesktopError::Backend(
                "the SFTP user must be a single word".to_string(),
            ));
        }
        Ok(())
    }

    /// The generated config file body.
    #[must_use]
    pub fn config(&self, port: u16) -> String {
        format!(
            "# Generated by Handfast for one session.\n\
             Port {port}\n\
             ListenAddress 127.0.0.1\n\
             PubkeyAuthentication yes\n\
             PasswordAuthentication no\n\
             KbdInteractiveAuthentication no\n\
             PermitRootLogin no\n\
             AllowUsers {user}\n\
             ChrootDirectory {root}\n\
             ForceCommand internal-sftp\n",
            user = self.user,
            root = self.root
        )
    }
}

/// A generated config plus the child that is reading it.
struct Running {
    child: Child,
    config_path: PathBuf,
}

/// Serves a directory over SFTP with a one-shot `sshd`.
///
/// The trait is defined here rather than in the plugin crate so the plugin can
/// stay free of process management.
#[async_trait]
pub trait SftpServerBackend: Send + Sync {
    /// Start serving, returning the port.
    ///
    /// # Errors
    /// Fails when the request is invalid or `sshd` cannot be started.
    async fn start(&self, request: &ServerRequest) -> Result<u16>;

    /// Stop the server.
    async fn stop(&self);
}

/// An [`SftpServerBackend`] backed by `sshd`.
#[derive(Default)]
pub struct SshdSftp {
    running: Mutex<Option<Running>>,
}

impl std::fmt::Debug for SshdSftp {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let running = self
            .running
            .lock()
            .map(|slot| slot.is_some())
            .unwrap_or(false);
        f.debug_struct("SshdSftp")
            .field("running", &running)
            .finish()
    }
}

impl SshdSftp {
    /// Build a backend that runs the real `sshd`.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Stop any running server. Used by [`Drop`] as well.
    fn stop_inner(&self) {
        let Ok(mut guard) = self.running.lock() else {
            return;
        };
        if let Some(mut running) = guard.take() {
            let _ = running.child.kill();
            let _ = running.child.wait();
            let _ = std::fs::remove_file(&running.config_path);
        }
    }
}

impl Drop for SshdSftp {
    fn drop(&mut self) {
        self.stop_inner();
    }
}

/// Pick a port the OS is not currently using.
fn free_port() -> Result<u16> {
    let listener = TcpListener::bind("127.0.0.1:0")
        .map_err(|error| DesktopError::Backend(format!("no free port: {error}")))?;
    listener
        .local_addr()
        .map(|address| address.port())
        .map_err(|error| DesktopError::Backend(format!("no local address: {error}")))
}

/// Write the generated config next to the session's temporary files.
fn write_config(body: &str) -> Result<PathBuf> {
    let path = std::env::temp_dir().join(format!("handfast-sshd-{}.conf", std::process::id()));
    let mut file = std::fs::File::create(&path)
        .map_err(|error| DesktopError::Backend(format!("config file: {error}")))?;
    file.write_all(body.as_bytes())
        .map_err(|error| DesktopError::Backend(format!("config write: {error}")))?;
    Ok(path)
}

#[async_trait]
impl SftpServerBackend for SshdSftp {
    async fn start(&self, request: &ServerRequest) -> Result<u16> {
        request.validate()?;
        self.stop_inner();

        let port = free_port()?;
        let config_path = write_config(&request.config(port))?;
        let child = Command::new(PROGRAM)
            .arg("-D")
            .arg("-e")
            .arg("-f")
            .arg(&config_path)
            .arg("-p")
            .arg(port.to_string())
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .spawn()
            .map_err(|error| {
                let _ = std::fs::remove_file(&config_path);
                match error.kind() {
                    std::io::ErrorKind::NotFound => {
                        DesktopError::Unsupported("sshd is not installed")
                    }
                    _ => DesktopError::Backend(format!("sshd: {error}")),
                }
            })?;

        if let Ok(mut guard) = self.running.lock() {
            *guard = Some(Running { child, config_path });
        }
        Ok(port)
    }

    async fn stop(&self) {
        self.stop_inner();
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn request() -> ServerRequest {
        ServerRequest {
            root: "/home/alice/Public".to_string(),
            user: "alice".to_string(),
        }
    }

    #[test]
    fn the_config_is_chrooted_and_loopback_only() {
        let config = request().config(5000);
        assert!(config.contains("Port 5000"));
        // Loopback only: the file server must not be reachable from the LAN.
        assert!(config.contains("ListenAddress 127.0.0.1"));
        assert!(config.contains("ChrootDirectory /home/alice/Public"));
        // Keys only: no password surface on a server started on demand.
        assert!(config.contains("PasswordAuthentication no"));
        assert!(config.contains("KbdInteractiveAuthentication no"));
        assert!(config.contains("PermitRootLogin no"));
        assert!(config.contains("AllowUsers alice"));
        assert!(config.contains("ForceCommand internal-sftp"));
    }

    #[test]
    fn a_relative_root_is_refused() {
        let mut request = request();
        request.root = "Public".to_string();
        assert!(request.validate().is_err());
    }

    #[test]
    fn a_newline_in_the_root_cannot_inject_a_directive() {
        let mut request = request();
        request.root = "/home/alice\nPasswordAuthentication yes".to_string();
        assert!(request.validate().is_err());
    }

    #[test]
    fn an_empty_root_is_refused() {
        let mut request = request();
        request.root = "   ".to_string();
        assert!(request.validate().is_err());
    }

    #[test]
    fn a_multi_word_user_is_refused() {
        let mut request = request();
        request.user = "alice root".to_string();
        assert!(request.validate().is_err());

        request.user = String::new();
        assert!(request.validate().is_err());
    }

    #[test]
    fn a_free_port_is_actually_bindable() {
        let port = free_port().unwrap();
        assert!(port > 0);
        // The port was released, so binding it again should work.
        assert!(TcpListener::bind(("127.0.0.1", port)).is_ok());
    }

    #[test]
    fn the_config_file_is_written() {
        let path = write_config(&request().config(5001)).unwrap();
        let text = std::fs::read_to_string(&path).unwrap();
        assert!(text.contains("Port 5001"));
        std::fs::remove_file(&path).unwrap();
    }

    #[tokio::test]
    async fn stopping_a_stopped_server_is_harmless() {
        let backend = SshdSftp::new();
        backend.stop().await;
        backend.stop().await;
    }

    #[tokio::test]
    async fn an_invalid_request_never_spawns() {
        let backend = SshdSftp::new();
        let mut request = request();
        request.root = "relative".to_string();
        assert!(backend.start(&request).await.is_err());
    }
}
